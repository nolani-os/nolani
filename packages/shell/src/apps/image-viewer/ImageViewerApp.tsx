/**
 * The viewer. Shows images — and also **running** web pages
 * (`.html`, `.htm`) as well as artifacts that Clara sends directly from the chat.
 *
 * Important: why here and not in a separate app: there should be ONE viewer.
 * Previously a page generated by Clara ended up in the text editor — the user
 * saw source code instead of their game.
 */

/**
 * Small prelude injected into the page.
 *
 * The frame deliberately runs WITHOUT `allow-same-origin` — the page thus has
 * its own empty origin and can reach neither cookies nor the shell.
 * Side effect: `localStorage` throws a SecurityError there. Many generated
 * games store their score in it and would crash with a white screen.
 * So the page gets an in-memory replacement.
 */
const VORBAU = `<script>
(function () {
  try { window.localStorage.getItem("probe"); return; } catch (e) {}
  var m = new Map();
  var ersatz = {
    getItem: function (k) { return m.has(String(k)) ? m.get(String(k)) : null; },
    setItem: function (k, v) { m.set(String(k), String(v)); },
    removeItem: function (k) { m.delete(String(k)); },
    clear: function () { m.clear(); },
    key: function (i) { return Array.from(m.keys())[i] || null; },
  };
  Object.defineProperty(ersatz, "length", { get: function () { return m.size; } });
  try {
    Object.defineProperty(window, "localStorage", { value: ersatz, configurable: true });
    Object.defineProperty(window, "sessionStorage", { value: ersatz, configurable: true });
  } catch (e) {}
})();
<\/script>`;

/** Insert the prelude right after <head> (otherwise at the very start). */
function mitVorbau(html: string): string {
  const treffer = /<head[^>]*>/i.exec(html);
  if (treffer) {
    const pos = treffer.index + treffer[0].length;
    return html.slice(0, pos) + VORBAU + html.slice(pos);
  }
  return VORBAU + html;
}

/** Image extensions the carousel pages through (tif/heif are displayable too). */
const BILD_ENDUNG = /\.(jpe?g|png|gif|webp|bmp|avif|heic|heif|tiff?|svg)$/i;

/**
 * URL of an image. Streamed (`/read` was limited to 10 MB). The browser cannot
 * render HEIC/TIFF itself ⇒ the API converts to JPEG (`/as-jpeg`).
 * Important: previously this used Nextcloud's preview — which generates NONE
 * for these formats, so HEIC/TIFF images stayed blank in the viewer.
 */
function bildUrl(source: string, path: string): string {
  const e = (path.split(".").pop() || "").toLowerCase();
  return e === "heic" || e === "heif" || e === "tif" || e === "tiff"
    ? `/api/claraos/files/v2/as-jpeg?source=${encodeURIComponent(source)}&path=${encodeURIComponent(path)}`
    : fileUrl(source, path, { inline: true });
}

export default function ImageViewerApp({ windowId }: { windowId: string }) {
  const [imageUrl, setImageUrl] = useState<string>("");
  // Important: the blob: URL to clean up must live in a ref, not in state.
  // The load effect's cleanup saw `imageUrl` from THE render in which the
  // effect was created — it was still empty then, so nothing was ever
  // released. As long as switching images meant a NEW window this went
  // unnoticed; since `betrachterZeigen` re-targets the same window, every
  // switch would otherwise leave an image behind in memory (~1 MB per
  // "make it brighter").
  const blobRef = useRef<string>("");
  const [imageName, setImageName] = useState("");
  // Zoom relative to fit (1 = whole image visible). Computed in YARL.
  const [zoom, setZoom] = useState(1);
  const zoomRef = useRef<ZoomRef>(null);

  // ── Page mode (.html / artifact) ─────────────────────────────────────────
  const [seite, setSeite] = useState<string>("");        // page source
  const [seiteFehler, setSeiteFehler] = useState("");
  const [quelltext, setQuelltext] = useState(false);     // source instead of rendered view
  const [neustart, setNeustart] = useState(0);           // counter = rebuild frame
  const rahmenRef = useRef<HTMLIFrameElement>(null);

  // Auto-load when opened with a file path/source.
  // Without a loading state the viewer showed the EMPTY state ("open image or
  // page…") during `readFile` — on a phone that looked as if loading had failed.
  const [laedt, setLaedt] = useState(false);
  const [waehlerOffen, setWaehlerOffen] = useState(false);
  const istHandy = useIsMobile();
  const setWindowFile = useWindowsStore((s) => s.setWindowFile);
  const closeWindow = useWindowsStore((s) => s.closeWindow);

  const winPath = useWindowsStore((s) => s.windows[windowId]?.path);
  const winSource = useWindowsStore((s) => s.windows[windowId]?.source);
  const winTitle = useWindowsStore((s) => s.windows[windowId]?.title);
  const setCurrentObjectUri = useWindowsStore((s) => s.setCurrentObjectUri);

  const ext = (winPath || "").split(".").pop()?.toLowerCase() || "";

  useEffect(() => {
    if (winPath && winSource) {
      setCurrentObjectUri(windowId, buildObjectUri("image-viewer", `${winSource}://${winPath}`));
    }
    return () => setCurrentObjectUri(windowId, undefined);
  }, [windowId, winPath, winSource, setCurrentObjectUri]);

  useEffect(() => {
    if (!winPath || !winSource) return;
    let cancelled = false;

    // Artifact: the content lives in memory, there is no file.
    if (winSource === "artefakt") {
      const a = holen(winPath);
      if (!a) {
        setSeiteFehler(
          "Dieses Artefakt ist nicht mehr da — die Seite wurde zwischendurch neu geladen. " +
          `Bitte ${getBrand().assistant} noch einmal darum bitten.`,
        );
        setImageUrl("");
        meldeInhalt(windowId, false,
          "Das Artefakt lag nicht mehr im Speicher (Seite wurde neu geladen) — nichts zu sehen.");
        return;
      }
      setSeiteFehler("");
      setSeite(a.inhalt);
      // Only real HTML runs — everything else (code, data, Markdown) is shown
      // as source instead of being executed as a page.
      setQuelltext(!istHtml(a.inhalt, a.mime));
      setImageUrl("");
      setImageName(a.titel || "Artefakt");
      setNeustart((n) => n + 1);
      meldeInhalt(windowId, true, istHtml(a.inhalt, a.mime)
        ? `Die Seite "${a.titel || "Artefakt"}" laeuft jetzt im Betrachter.`
        : `"${a.titel || "Artefakt"}" steht als Quelltext im Betrachter.`);
      return;
    }

    // Images straight from the streaming endpoint — /read was limited to 10 MB
    // (phone photos and scans exceeded that, the viewer stayed blank). The browser
    // cannot render HEIC/TIFF itself ⇒ converted to JPEG server-side (see bildUrl).
    if (ext !== "html" && ext !== "htm") {
      const url = bildUrl(winSource, winPath);
      setSeite("");
      if (blobRef.current) URL.revokeObjectURL(blobRef.current);
      blobRef.current = "";
      setImageUrl(url);
      setImageName(winTitle || winPath.split("/").pop() || "image");
      // Important: only report once the image is REALLY there (probe below).
      // Previously it said "is visible" even for a file that didn't exist.
      return;
    }

    setLaedt(true);
    (async () => {
      const data = await useFileStore.getState().readFile(winSource, winPath);
      if (cancelled) return;
      setLaedt(false);
      if (!data) {
        if (ext === "html" || ext === "htm") {
          setSeiteFehler(`Datei ${winPath} konnte nicht geladen werden.`);
        }
        meldeInhalt(windowId, false,
          `Die Datei ${winPath} liess sich nicht laden — der Betrachter ist leer.`);
        return;
      }
      const dateiExt = (winPath.split(".").pop() || "").toLowerCase();

      // ── Web page: run it in a frame, don't treat it as an image ─────────────
      if (dateiExt === "html" || dateiExt === "htm") {
        const roh = data.encoding === "utf-8"
          ? data.content
          : new TextDecoder().decode(
              Uint8Array.from(atob(data.content), (c) => c.charCodeAt(0)),
            );
        setSeiteFehler("");
        setSeite(roh);
        setQuelltext(false);
        setImageUrl("");
        setImageName(winTitle || winPath.split("/").pop() || "Seite");
        setNeustart((n) => n + 1);
        meldeInhalt(windowId, true, `${winPath} laeuft jetzt als Seite im Betrachter.`);
        return;
      }

      // Backend returns { content, encoding }: utf-8 (text) or base64 (binary)
      const mime = dateiExt === "svg" ? "image/svg+xml"
        : dateiExt === "png" ? "image/png"
        : dateiExt === "gif" ? "image/gif"
        : dateiExt === "webp" ? "image/webp"
        : dateiExt === "bmp" ? "image/bmp"
        : dateiExt === "ico" ? "image/x-icon"
        : dateiExt === "avif" ? "image/avif"
        : "image/jpeg";
      let url: string;
      if (data.encoding === "utf-8") {
        // SVG/text-image
        const blob = new Blob([data.content], { type: mime });
        url = URL.createObjectURL(blob);
      } else {
        // base64 → blob (cheaper for memory than huge data: URLs)
        const bin = atob(data.content);
        const bytes = new Uint8Array(bin.length);
        for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
        const blob = new Blob([bytes], { type: mime });
        url = URL.createObjectURL(blob);
      }
      setSeite("");
      if (blobRef.current) URL.revokeObjectURL(blobRef.current);
      blobRef.current = url;
      setImageUrl(url);
      setImageName(winTitle || winPath.split("/").pop() || "image");
      meldeInhalt(windowId, true, `${winPath} ist im Betrachter zu sehen.`);
    })();
    return () => {
      cancelled = true;
      setLaedt(false);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [winPath, winSource]);

  // Release the last image when the window closes.
  useEffect(() => () => {
    if (blobRef.current) URL.revokeObjectURL(blobRef.current);
    blobRef.current = "";
  }, []);

  // ── Loading and error state of the CURRENT image ─────────────────────────
  // YARL only shows a red icon without text on error. Hence a probe of our
  // own: it reports to Clara (only after loading) and distinguishes
  // "does not exist" from "the browser cannot display it".
  const [bildStatus, setBildStatus] = useState<"laedt" | "ok" | "fehler">("laedt");
  const [fehlerText, setFehlerText] = useState("");
  useEffect(() => {
    if (!imageUrl || !winPath || winSource === "artefakt") return;
    let weg = false;
    setBildStatus("laedt");
    const probe = new Image();
    probe.onload = () => {
      if (weg) return;
      setBildStatus("ok");
      meldeInhalt(windowId, true, `${winPath} ist im Betrachter zu sehen.`);
    };
    probe.onerror = async () => {
      if (weg) return;
      const grund = await ladeGrund(imageUrl, "Bild");
      if (weg) return;
      setFehlerText(grund);
      setBildStatus("fehler");
      meldeInhalt(windowId, false, `${winPath} konnte nicht angezeigt werden: ${grund}`);
    };
    probe.src = imageUrl;
    return () => { weg = true; probe.onload = null; probe.onerror = null; };
  }, [imageUrl, winPath, winSource, windowId]);

  // Phone: tapping hides the toolbar (like Google Photos). Delayed so that
  // a double tap (= zoom) doesn't toggle the toolbar twice.
  const [leisteAus, setLeisteAus] = useState(false);
  const tippUhr = useRef<number | undefined>(undefined);
  const aufTipp = useCallback(() => {
    if (!istHandy) return;
    if (tippUhr.current) { window.clearTimeout(tippUhr.current); tippUhr.current = undefined; return; }
    tippUhr.current = window.setTimeout(() => {
      tippUhr.current = undefined;
      setLeisteAus((a) => !a);
    }, 280);
  }, [istHandy]);
  useEffect(() => () => window.clearTimeout(tippUhr.current), []);

  const seiteFertig = useMemo(() => (seite ? mitVorbau(seite) : ""), [seite]);

  // Neighbouring images in the same folder — the carousel pages through them.
  // Important: in the SAME order as the Files app. Previously the viewer sorted
  // by name on its own; anyone who had set "newest first" there ended up
  // somewhere else entirely when paging. The setting lives in the shared file
  // store, and the sort is the same function.
  const [ordnerInhalt, setOrdnerInhalt] = useState<FileNode[]>([]);
  const [nachbarIdx, setNachbarIdx] = useState(-1);
  const sortKey = useFileStore((s) => s.sortKey);
  const sortDir = useFileStore((s) => s.sortDir);
  const groupBy = useFileStore((s) => s.groupBy);
  const showHidden = useFileStore((s) => s.showHidden);
  const nachbarn = useMemo(() =>
    prepareItems(ordnerInhalt, { sortKey, sortDir, groupBy, showHidden, dirsFirst: false, filterQuery: "" })
      .flatMap((g) => g.items)
      .filter((k) => !k.isDir && BILD_ENDUNG.test(k.name))
      .map((k) => ({ path: k.path, name: k.name })),
  [ordnerInhalt, sortKey, sortDir, groupBy, showHidden]);

  // Fetch folder contents ONCE per folder, not per image: when paging only
  // the path changes, the folder stays the same.
  const ordner = useMemo(() => {
    if (!winPath || winSource === "artefakt") return "";
    const i = winPath.lastIndexOf("/");
    return i <= 0 ? "/" : winPath.slice(0, i);
  }, [winPath, winSource]);

  useEffect(() => {
    if (!ordner || !winSource || winSource === "artefakt") { setOrdnerInhalt([]); return; }
    let weg = false;
    (async () => {
      try {
        const r = await fetch(`/api/claraos/files/v2/tree?source=${encodeURIComponent(winSource)}`
                              + `&path=${encodeURIComponent(ordner)}&depth=1`);
        if (!r.ok || weg) return;
        const baum = await r.json();
        if (!weg) setOrdnerInhalt((baum?.children || []) as FileNode[]);
      } catch {
        // Important: silently leave it empty: without a list there is no paging,
        // but zooming and panning keep working. An error here must not cripple
        // the viewer.
        if (!weg) setOrdnerInhalt([]);
      }
    })();
    return () => { weg = true; };
  }, [ordner, winSource]);

  useEffect(() => {
    setNachbarIdx(nachbarn.findIndex((b) => b.path === winPath));
  }, [nachbarn, winPath]);

  // The sequence for the carousel. If the current image is not in the folder
  // list (list still loading, preview endpoint, artifact), it stands alone.
  const folge = useMemo(() => {
    if (winSource && nachbarIdx >= 0) {
      return nachbarn.map((b) => ({ src: bildUrl(winSource, b.path), alt: b.name }));
    }
    return imageUrl ? [{ src: imageUrl, alt: imageName }] : [];
  }, [nachbarn, nachbarIdx, winSource, imageUrl, imageName]);
  const folgeIdx = nachbarIdx >= 0 ? nachbarIdx : 0;

  /** The carousel switched ⇒ the WINDOW now shows this file. */
  const aufAnsicht = useCallback(({ index }: { index: number }) => {
    const b = nachbarn[index];
    if (!b || !winSource || b.path === winPath) return;
    // Important: title, object URI and the report to Clara hang off the window —
    // so don't just swap the image, re-target the window.
    setWindowFile(windowId, winSource, b.path, b.name);
  }, [nachbarn, winSource, winPath, windowId, setWindowFile]);

  /** 1:1 = one image pixel per screen pixel, measured on the image currently shown. */
  const einsZuEins = useCallback(() => {
    const z = zoomRef.current;
    const img = rahmenBildRef.current?.querySelector<HTMLImageElement>(".yarl__slide_current img");
    if (!z || !img || !img.naturalWidth) return;
    const breite = img.getBoundingClientRect().width / (z.zoom || 1);
    if (breite > 0) z.changeZoom(Math.min(img.naturalWidth / breite, z.maxZoom));
  }, []);
  const rahmenBildRef = useRef<HTMLDivElement>(null);

  // ── Marker / region selection ──────────────────────────────────────────
  const markerMode = useMarkerStore((s) => s.mode);
  const setPinned = useMarkerStore((s) => s.setPinned);
  const cancelPicking = useMarkerStore((s) => s.cancelPicking);
  const [overlayBlob, setOverlayBlob] = useState<Blob | null>(null);

  // When user clicks 📍 in the chat, fetch the current image as a blob and
  // mount MarkerOverlay over it. Cancelling clears both the overlay and the
  // store's picking mode.
  useEffect(() => {
    if (markerMode !== "picking") {
      setOverlayBlob(null);
      return;
    }
    if (!imageUrl) return;
    let cancelled = false;
    fetch(imageUrl)
      .then((r) => r.blob())
      .then((blob) => { if (!cancelled) setOverlayBlob(blob); })
      .catch(() => { if (!cancelled) cancelPicking(); });
    return () => { cancelled = true; };
  }, [markerMode, imageUrl, cancelPicking]);

  const handleMarkerConfirm = useCallback((annotatedDataUrl: string, state?: import("markerjs2").MarkerAreaState) => {
    // Strip "data:image/png;base64," prefix to get raw base64.
    const b64 = annotatedDataUrl.split(",", 2)[1] ?? "";
    const objectUri = winSource && winPath ? buildObjectUri("image-viewer", `${winSource}://${winPath}`) : undefined;
    const bboxPx = computeBboxFromState(state);
    setPinned({
      kind: "bbox-img",
      appId: "image-viewer",
      objectUri,
      snapshotB64: b64,
      capturedAt: new Date().toISOString(),
      ...(bboxPx ? { bboxPx } : {}),
    });
    setOverlayBlob(null);
  }, [setPinned, winSource, winPath]);

  const handleMarkerCancel = useCallback(() => {
    cancelPicking();
    setOverlayBlob(null);
  }, [cancelPicking]);

  const zeigtSeite = !!seiteFertig;

  const zeigtLeiste = !(istHandy && leisteAus && !zeigtSeite);

  return (
    <div className={css.wurzel}>
      <div className={zeigtLeiste ? css.leiste : css.leisteAus}>
        {istHandy && (
          <button onClick={() => closeWindow(windowId)} className={css.knopf}
            aria-label="Zurück zu den Dateien" title="Zurück">
            <Icon name="back" size={20} />
          </button>
        )}
        {/* This used to be a native <input type="file">. On Android the system
            offered the gallery for it and launched Google Photos — outside of
            ClaraOS. Now you pick in the ClaraOS file picker, the same on BOTH
            platforms. */}
        <button onClick={() => setWaehlerOffen(true)} className={css.knopf}
          aria-label="Anderes Bild öffnen" title="Anderes Bild öffnen">
          <Icon name="folder" size={18} />{!istHandy && "Öffnen"}
        </button>
        {zeigtSeite ? (
          <>
            <button onClick={() => setNeustart((n) => n + 1)} className={css.knopf}
              title="Seite neu starten"><Icon name="reload" size={16} />Neu starten</button>
            <button onClick={() => setQuelltext((q) => !q)} className={css.knopf}>
              {quelltext ? "Ansicht" : "Quelltext"}
            </button>
          </>
        ) : imageUrl && bildStatus !== "fehler" ? (
          <>
            <span className={css.gruppe}>
              <button onClick={() => zoomRef.current?.zoomOut()} className={css.knopf}
                aria-label="Verkleinern" title="Verkleinern (−)">−</button>
              {/* Relative to fit: "Fit" is the normal state, not "100 %".
                  Previously this showed 100 % while only 5 % of the photo was visible. */}
              {!istHandy && (
                <span className={css.zoomText}>
                  {zoom <= 1.001 ? "Eingepasst" : `${Math.round(zoom * 100)} %`}
                </span>
              )}
              <button onClick={() => zoomRef.current?.zoomIn()} className={css.knopf}
                aria-label="Vergrößern" title="Vergrößern (+)">+</button>
            </span>
            {/* On phones double tap fits — space is lacking there, and without
                this omission the toolbar pushed name and position out of view. */}
            {!istHandy && (
              <>
                <button onClick={() => zoomRef.current?.changeZoom(1)} className={css.knopf}
                  title="Ganzes Bild zeigen">Einpassen</button>
                <button onClick={einsZuEins} className={css.knopf}
                  title="Originalgröße: ein Bildpixel pro Bildschirmpixel">1:1</button>
              </>
            )}
          </>
        ) : null}
        <span className={css.luecke} />
        {imageName && <span className={css.name} title={winPath}>{imageName}</span>}
        {/* Without this indicator paging is invisible — a gesture nobody
            knows about practically doesn't exist. */}
        {nachbarn.length > 1 && nachbarIdx >= 0 && !zeigtSeite && (
          <span className={css.position}>{nachbarIdx + 1}/{nachbarn.length}</span>
        )}
      </div>

      <div ref={rahmenBildRef} className={css.flaeche}>
        {overlayBlob && (
          <MarkerOverlay
            imageBlob={overlayBlob}
            onConfirm={handleMarkerConfirm}
            onCancel={handleMarkerCancel}
          />
        )}
        {zeigtSeite && quelltext ? (
          <pre className={css.quelltext}>{seite}</pre>
        ) : zeigtSeite ? (
          <iframe
            key={neustart}
            ref={rahmenRef}
            title={imageName || "Seite"}
            srcDoc={seiteFertig}
            onLoad={() => rahmenRef.current?.focus()}
            // Without allow-same-origin: own, empty origin. The page can reach
            // neither cookies nor the shell. allow-modals/pointer-lock so that
            // games can use alert() and pointer capture.
            sandbox="allow-scripts allow-modals allow-pointer-lock allow-popups"
            className={css.seite}
          />
        ) : imageUrl && bildStatus === "fehler" && nachbarIdx < 0 ? (
          // A single image that fails to load: a clear message instead of an icon.
          // (In the carousel the notice stays INSIDE the slide so you can keep paging.)
          <div className={css.hinweis} role="alert">
            <Icon name="warning" size={40} className={css.fehlerSymbol} />
            <div className={css.hinweisTitel}>„{imageName}“ konnte nicht geladen werden</div>
            <div className={css.hinweisText}>{fehlerText}</div>
            <button className={css.hauptknopf} onClick={() => setWaehlerOffen(true)}>
              Anderes Bild öffnen
            </button>
          </div>
        ) : imageUrl && folge.length ? (
          // Important: gestures, keyboard, wheel, double click, bounds and preloading
          // come from YARL. `touch-action`, non-passive wheel listeners and the anchor
          // maths for pinching therefore do NOT need to live here any more.
          <Lightbox
            plugins={[Inline, Zoom]}
            inline={{ style: { width: "100%", height: "100%" } }}
            slides={folge}
            index={folgeIdx}
            on={{
              view: aufAnsicht,
              zoom: ({ zoom: z }) => setZoom(z),
              click: aufTipp,
            }}
            // Deliberately NO wrap-around at the end of the folder: a silent
            // jump to the start reads like an error.
            carousel={{ finite: true, preload: 1, padding: 0, spacing: "10%", imageFit: "contain" }}
            // maxZoomPixelRatio 3: small images can be enlarged too
            // (default 1 = never beyond original size).
            zoom={{ ref: zoomRef, maxZoomPixelRatio: 3, scrollToZoom: true, doubleClickMaxStops: 2,
                    // v4 pinch: magnification follows finger spread (v3 stopped at 1.8×)
                    pinchZoomV4: true }}
            animation={{ swipe: 250, zoom: 200 }}
            labels={{
              Previous: "Vorheriges Bild", Next: "Nächstes Bild",
              "Zoom in": "Vergrößern", "Zoom out": "Verkleinern",
              Carousel: "Bilder", Slide: "Bild", "Photo gallery": "Bilder im Ordner",
            }}
            render={{
              // Remove the plugin's zoom buttons: zooming happens via OUR toolbar.
              buttonZoom: () => null,
              // YARL's red icon without text → a message in ClaraOS colours
              iconError: () => (
                <div className={css.hinweis} role="alert">
                  <Icon name="warning" size={32} className={css.fehlerSymbol} />
                  <div className={css.hinweisText}>
                    {fehlerText || "Dieses Bild ließ sich nicht laden."}
                  </div>
                </div>
              ),
              iconLoading: () => <div className={css.kreisel} aria-label="Bild wird geladen" />,
              // On phones you swipe; arrow buttons only cover the image there.
              ...(istHandy || folge.length < 2
                ? { buttonPrev: () => null, buttonNext: () => null } : {}),
            }}
            toolbar={{ buttons: [] }}
            styles={{ container: { backgroundColor: "transparent" } }}
          />
        ) : laedt ? (
          <div className={css.hinweis}>
            <div className={css.kreisel} />
            <div className={css.hinweisTitel}>
              {(winPath || "").split("/").pop() || "Datei"} wird geladen …
            </div>
          </div>
        ) : (
          <div className={css.hinweis}>
            <Icon name={seiteFehler ? "warning" : "image"} size={48}
              className={seiteFehler ? css.fehlerSymbol : undefined} />
            <div className={css.hinweisTitel}>
              {seiteFehler || "Bild oder Seite öffnen, um sie anzusehen"}
            </div>
            {!seiteFehler && (
              <div className={css.hinweisText}>
                JPG, PNG, GIF, WebP, HEIC, TIFF, SVG — und HTML-Seiten, die laufen
              </div>
            )}
            <button className={css.hauptknopf} onClick={() => setWaehlerOffen(true)}>
              Bild auswählen
            </button>
          </div>
        )}
      </div>

      {/* ClaraOS's own file picker — no system dialog, so that Google Photos
          does not open on phones. Returns only the file REF; the load effect
          above then pulls in the content in the SAME window. */}
      <FilePickerModal
        open={waehlerOffen}
        onClose={() => setWaehlerOffen(false)}
        mimePrefix="image/"
        onPickRefs={(refs) => {
          setWaehlerOffen(false);
          const r = refs[0];
          if (r) setWindowFile(windowId, r.source, r.path, r.name);
        }}
      />
    </div>
  );
}
